using System.IO.Compression;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using ElecStock.Contracts;
using ElecStock.Data.Entities;
using ElecStock.Data.Files;
using ElecStock.Kicad;
using Microsoft.EntityFrameworkCore;

namespace ElecStock.Data.Services;

/// <summary>
/// The stock KiCad library as files: the items stored in <c>cad/</c> written out as <c>KiCad/Stock.kicad_sym</c>
/// (every symbol merged), <c>KiCad/Stock.pretty/</c> (footprints, their models pointed at the library) and
/// <c>KiCad/3D/</c>, plus a manifest the sync script uses to know which files it owns.
/// </summary>
public sealed class KicadLibrary(IDbContextFactory<StockDb> dbFactory, FileStore files)
{
    public const string ManifestFile = "elecstock-library.json";
    /// <summary>Bumped when the written layout changes, so every PC syncs again.</summary>
    const int Layout = 1;

    /// <summary>Short hash of the items (a replaced file has a new storage path): equal versions, equal libraries.</summary>
    public static string Version(IEnumerable<KicadItem> items)
    {
        var sb = new StringBuilder($"layout {Layout}\n");
        foreach (var i in items.OrderBy(i => i.Kind).ThenBy(i => i.Name, StringComparer.OrdinalIgnoreCase))
            sb.Append($"{i.Kind}|{i.Name}|{i.StoragePath}\n");
        return Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(sb.ToString())))[..12];
    }

    public async Task<string> VersionAsync(CancellationToken ct)
    {
        await using var db = await dbFactory.CreateDbContextAsync(ct);
        return Version(await db.KicadItems.AsNoTracking().ToListAsync(ct));
    }

    /// <summary>The library as a zip whose root is the folder <c>ELEC_STOCK</c> points to.</summary>
    public async Task<string> WriteZipAsync(Stream output, CancellationToken ct)
    {
        List<KicadItem> items;
        await using (var db = await dbFactory.CreateDbContextAsync(ct))
            items = await db.KicadItems.AsNoTracking().ToListAsync(ct);

        // ZipArchive writes synchronously: build it in a temp file, then stream it out.
        await using var temp = new FileStream(Path.GetTempFileName(), FileMode.Create, FileAccess.ReadWrite, FileShare.None, 81920, FileOptions.DeleteOnClose);
        string version;
        using (var zip = new ZipArchive(temp, ZipArchiveMode.Create, leaveOpen: true))
            version = Write(zip, items, manifest: true);
        temp.Position = 0;
        await temp.CopyToAsync(output, ct);
        return version;
    }

    /// <summary>Writes the <c>KiCad/</c> folder into <paramref name="zip"/> (and the manifest); returns the version.</summary>
    public string Write(ZipArchive zip, List<KicadItem> items, bool manifest)
    {
        var written = new List<string>();
        void Add(string path, byte[] content, CompressionLevel level = CompressionLevel.Optimal)
        {
            var entry = zip.CreateEntry(path, level);
            using var stream = entry.Open();
            stream.Write(content);
            written.Add(path);
        }

        var present = items.Where(i => files.Exists(i.StoragePath)).ToList();
        var symbols = present.Where(i => i.Kind == KicadItemKind.Symbol).Select(i => File.ReadAllText(files.FullPath(i.StoragePath))).ToList();
        Add(KicadLib.SymbolFile, Utf8(KicadFiles.MergeSymbols(symbols)));

        var resolve = ModelResolver(present);
        foreach (var fp in present.Where(i => i.Kind == KicadItemKind.Footprint).OrderBy(i => i.Name, StringComparer.OrdinalIgnoreCase))
            Add($"{KicadLib.FootprintDir}/{fp.Name}.kicad_mod", Utf8(KicadFiles.LinkModels(File.ReadAllText(files.FullPath(fp.StoragePath)), resolve)));

        foreach (var model in present.Where(i => i.Kind == KicadItemKind.Model).OrderBy(i => i.Name, StringComparer.OrdinalIgnoreCase))
            Add($"{KicadLib.ModelDir}/{model.Name}", File.ReadAllBytes(files.FullPath(model.StoragePath)));

        Add("KiCad/README.md", Utf8(Readme(present)));

        var version = Version(items);
        if (manifest)
            Add(ManifestFile, Utf8(JsonSerializer.Serialize(new { version, files = written }, new JsonSerializerOptions { WriteIndented = true })));
        return version;
    }

    /// <summary>Model file name → its library path, for the models of the library (case-insensitive, like Windows).</summary>
    public static Func<string, string?> ModelResolver(IEnumerable<KicadItem> items)
    {
        var models = items.Where(i => i.Kind == KicadItemKind.Model).ToDictionary(i => i.Name, StringComparer.OrdinalIgnoreCase);
        return file => models.TryGetValue(file, out var m) ? KicadLib.ModelPath(m.Name) : null;
    }

    static string Readme(List<KicadItem> items)
    {
        var sb = new StringBuilder();
        sb.Append("# Stock KiCad library\n\n");
        sb.Append("Generated by the ElecStock server: do not edit, changes are lost at the next sync. Add or replace files in\n");
        sb.Append("ElecStock (part pane → KiCad, or Settings → KiCad library).\n\n");
        sb.Append($"Path variable `{KicadLib.PathVariable}` = the folder holding this `KiCad/` folder. Library tables, nickname `{KicadLib.Nickname}`:\n\n");
        sb.Append($"- symbols: `${{{KicadLib.PathVariable}}}/{KicadLib.SymbolFile}`\n");
        sb.Append($"- footprints: `${{{KicadLib.PathVariable}}}/{KicadLib.FootprintDir}`\n\n");
        foreach (var kind in Enum.GetValues<KicadItemKind>())
        {
            var list = items.Where(i => i.Kind == kind).OrderBy(i => i.Name, StringComparer.OrdinalIgnoreCase).ToList();
            if (list.Count == 0) continue;
            sb.Append(kind switch { KicadItemKind.Symbol => "## Symbols\n\n", KicadItemKind.Footprint => "## Footprints\n\n", _ => "## 3D models\n\n" });
            sb.Append("| Name | Source |\n|---|---|\n");
            foreach (var i in list)
                sb.Append($"| `{i.Name}` | {i.Source.Replace("|", "\\|").Replace("\n", " ")} |\n");
            sb.Append('\n');
        }
        return sb.ToString();
    }

    static byte[] Utf8(string text) => new UTF8Encoding(false).GetBytes(text);

    // ---------- storing uploaded items ----------

    public sealed record UpsertResult(List<KicadItem> Added, List<KicadItem> Replaced, List<string> OldFiles);

    /// <summary>
    /// Adds the files to the library, replacing the items of the same kind and name. The new files are written now;
    /// the replaced ones are returned in <see cref="UpsertResult.OldFiles"/>, to trash once the database is saved.
    /// </summary>
    public static async Task<UpsertResult> UpsertAsync(StockDb db, FileStore files, List<KicadFile> uploads, DateTimeOffset now, CancellationToken ct)
    {
        var duplicate = uploads.GroupBy(u => (u.Kind, u.Name.ToLowerInvariant())).FirstOrDefault(g => g.Count() > 1);
        if (duplicate != null) throw new StockException($"The {KicadLib.Title(duplicate.Key.Kind)} '{duplicate.First().Name}' is twice in the upload.");

        var existing = await db.KicadItems.ToListAsync(ct);
        var symbolNames = existing.Where(i => i.Kind == KicadItemKind.Symbol).Select(i => i.Name)
            .Concat(uploads.Where(u => u.Kind == KicadItemKind.Symbol).Select(u => u.Name))
            .ToHashSet(StringComparer.OrdinalIgnoreCase);
        foreach (var u in uploads.Where(u => u.Extends != null && !symbolNames.Contains(u.Extends)))
            throw new StockException($"The symbol '{u.Name}' extends '{u.Extends}', which is not in the library: upload both together.");

        var result = new UpsertResult([], [], []);
        foreach (var u in uploads)
        {
            var path = await files.SaveAsync(FileStore.CadDir, u.Extension, u.Content, ct);
            var item = existing.FirstOrDefault(i => i.Kind == u.Kind && i.Name.Equals(u.Name, StringComparison.OrdinalIgnoreCase));
            if (item == null)
            {
                item = new KicadItem { Kind = u.Kind, Name = u.Name, StoragePath = path, CreatedAt = now };
                db.KicadItems.Add(item);
                result.Added.Add(item);
            }
            else
            {
                result.OldFiles.Add(item.StoragePath);
                item.Name = u.Name;
                item.StoragePath = path;
                result.Replaced.Add(item);
            }
            item.Size = u.Content.Length;
            item.Extends = u.Extends;
            item.UpdatedAt = now;
        }
        return result;
    }
}
